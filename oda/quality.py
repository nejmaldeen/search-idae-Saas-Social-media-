"""Content quality gate.

Real-world search results contain a lot of text that is NOT a user describing a
problem: SEO/content-marketing spam, agency service listings, and bot-generated
issue templates. Letting that through would put fabricated-looking "market
evidence" in the report, which is the one thing this system must not do.

Every rejection is recorded with a reason so the filter is auditable and can be
loosened deliberately rather than silently.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

ACCEPT, WEAK, REJECT = "accept", "weak", "reject"

# --- promotional / agency-services language -------------------------------
_PROMO = [
    (r"\bservices?\s+in\s+[A-Z][a-z]{3,}", "geo-targeted service listing (SEO spam shape)"),
    (r"\b(?:we|our company|our team)\s+(?:offer|provide|deliver|specialis|specializ)", "vendor pitch"),
    (r"\bour\s+(?:services|solutions|platform|company|agency|experts)\b", "vendor self-reference"),
    (r"\b(?:hire|choose|contact)\s+(?:us|our|the best)\b", "call to action"),
    (r"\bbest\s+[\w\s]{3,30}\s+(?:company|agency|provider|services)\b", "superlative vendor copy"),
    (r"\b(?:can|also)\s+(?:bring together|benefit from|help businesses)\b", "generic listicle copy"),
    (r"\b(?:book a demo|sign up (?:now|today)|get started today|free consultation)\b", "CTA"),
    (r"\b(?:solutions?|services)\s+(?:provider|company)\b", "vendor descriptor"),
    (r"\b(?:businesses|companies|enterprises)\s+(?:modernizing|looking to|that want)\b", "marketing audience framing"),
    (r"\b(?:boost|increase|improve)\s+your\s+(?:sales|revenue|business|roi)\b", "marketing promise"),
    (r"سجل الآن|تواصل معنا|أفضل شركة|خدماتنا|نحن نقدم|احصل على خصم", "Arabic promotional copy"),
    (r"كود خصم|كوبون|رابط الموقع|رابط التسجيل|اشترك الان|اشترك الآن|"
     r"\bdiscount code\b|\bpromo code\b|\buse code\b|\baffiliate link\b", "discount/affiliate promotion"),
]
PROMO = [(re.compile(rx, re.IGNORECASE | re.UNICODE), why) for rx, why in _PROMO]

# --- bot / template generated issue bodies --------------------------------
_BOT = [
    (r"\b[A-Z][A-Z0-9]*(?:-[A-Z0-9]+){2,}-\d{6,}\b", "machine-generated tracking identifier"),
    (r"\b(?:authorized implementation WIP|automated run|auto-generated|generated by)\b", "self-declared automation"),
    (r"\[ASO\]|\breview analysis\b\s*\(\d{4}-\d{2}-\d{2}\)", "automated report template"),
    (r"\bdependabot\b|\brenovate\[bot\]\b|\bgithub-actions\[bot\]\b", "known bot author pattern"),
]
BOT = [(re.compile(rx, re.IGNORECASE | re.MULTILINE | re.UNICODE), why) for rx, why in _BOT]

FIRST_PERSON = re.compile(
    r"\b(?:i|i'm|im|i've|ive|my|we|we're|were|we've|our|us|me)\b|"
    # Arabic first person: pronouns, possessives, and the verb prefixes that
    # carry "I/we" without a separate pronoun (أ-/ن- + past-tense -ت).
    r"أنا|انا|نحن|احنا|إحنا|"
    r"عندي|لدي|عندنا|لدينا|لي\b|لنا\b|عندى|"
    r"متجري|شركتي|مشروعي|موقعي|حسابي|عملي|شغلي|زبائني|عملائي|"
    r"(?:أ|ا)(?:درس|عمل|حاول|بحث|ستخدم|واجه|بي|ريد|حتاج|قدر|عرف|فهم)|"
    r"(?:جرب|حاول|واجه|عانى|عاني|اشتري|اشتريت|بدأ|بديت|سويت|صار|شفت|لقيت|قعدت|ضيعت|تعبت)ت?\b|"
    r"ن(?:ستخدم|عاني|واجه|حتاج|بحث|حاول)",
    re.IGNORECASE | re.UNICODE)

_MD_LINK = re.compile(r"\[[^\]]*\]\([^)]*\)|https?://\S+")
_CODE_FENCE = re.compile(r"```")
_HEADER = re.compile(r"^\s*#{1,6}\s+\S", re.MULTILINE)
_CHECKBOX = re.compile(r"^\s*[-*]\s*\[[ xX]\]", re.MULTILINE)

MAX_LINK_DENSITY = 0.14     # fraction of characters inside links/URLs
MAX_HEADER_RATIO = 0.34     # fraction of non-empty lines that are markdown headers


@dataclass
class Quality:
    verdict: str
    reasons: list[str] = field(default_factory=list)
    first_person: bool = False
    link_density: float = 0.0
    header_ratio: float = 0.0

    @property
    def usable(self) -> bool:
        return self.verdict != REJECT


def assess(text: str) -> Quality:
    t = (text or "").strip()
    if not t:
        return Quality(REJECT, ["empty"])

    reasons: list[str] = []

    for rx, why in PROMO:
        if rx.search(t):
            reasons.append(f"promotional: {why}")
            break
    for rx, why in BOT:
        if rx.search(t):
            reasons.append(f"bot/template: {why}")
            break

    link_chars = sum(len(m.group(0)) for m in _MD_LINK.finditer(t))
    link_density = link_chars / max(1, len(t))
    if link_density > MAX_LINK_DENSITY:
        reasons.append(f"link-heavy body ({link_density:.0%} of characters are links)")

    lines = [l for l in t.splitlines() if l.strip()]
    header_ratio = (len(_HEADER.findall(t)) / len(lines)) if lines else 0.0
    if header_ratio > MAX_HEADER_RATIO and len(lines) > 4:
        reasons.append(f"structured template ({header_ratio:.0%} of lines are headers)")
    if len(_CHECKBOX.findall(t)) >= 5:
        reasons.append("checklist template body")
    if len(_CODE_FENCE.findall(t)) >= 4:
        reasons.append("mostly code blocks")

    fp = bool(FIRST_PERSON.search(t))
    if not fp:
        reasons.append("no first-person voice; reads as description rather than lived experience")

    hard = [r for r in reasons if r.startswith(("promotional:", "bot/template:"))
            or "link-heavy" in r or "structured template" in r or "checklist template" in r
            or "mostly code blocks" in r]
    if hard:
        verdict = REJECT
    elif not fp:
        verdict = WEAK
    else:
        verdict = ACCEPT
    return Quality(verdict, reasons, first_person=fp,
                   link_density=round(link_density, 3), header_ratio=round(header_ratio, 3))
